import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'legacy-redirects.json'), 'utf8'));
const check = process.argv.includes('--check');
const escape = (text) => text.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
function validateTarget(target) {
  const url = new URL(target);
  if (!['https://blog.lazying.art', 'https://lazying.art'].includes(url.origin) || url.search || url.hash || url.username || url.password) throw Error(`Unreviewed destination: ${target}`);
}
function emit(relative, body) {
  const file = path.join(root, relative);
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== body) throw Error(`Stale generated file: ${relative}`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, body);
  }
}
for (const [source, target] of Object.entries(manifest.pages)) {
  validateTarget(target);
  if (!/^\/(en\/|zh\/|html\/)/.test(source) || source.includes('..') || /[?#\\]/.test(source)) throw Error(`Unsafe source: ${source}`);
  // Directory form accepts both trailing-slash variants on GitHub Pages.
  emit(source.replace(/^\//, '').replace(/\/$/, '') + '/index.html', `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>This page has moved — LazyingArt</title>
  <link rel="canonical" href="${escape(target)}">
  <meta http-equiv="refresh" content="0; url=${escape(target)}">
</head>
<body><main><h1>This page has moved</h1><p><a href="${escape(target)}">Continue to the current page</a>.</p></main></body>
</html>
`);
}
for (const [id, target] of Object.entries(manifest.postIds)) {
  if (!/^[1-9][0-9]*$/.test(id)) throw Error('Invalid post ID');
  validateTarget(target);
}
emit('legacy-post-redirect.js', `// Generated by tools/build-legacy-redirects.mjs. Only verified public posts.
(() => {
  if (!['/', '/index.html'].includes(window.location.pathname)) return;
  const params = new URLSearchParams(window.location.search);
  if (params.getAll('p').length !== 1) return;
  const posts = ${JSON.stringify(manifest.postIds, null, 2)};
  const id = params.get('p');
  if (Object.prototype.hasOwnProperty.call(posts, id)) window.location.replace(posts[id]);
})();
`);
console.log(`${check ? 'Verified' : 'Generated'} ${Object.keys(manifest.pages).length} exact path redirects and ${Object.keys(manifest.postIds).length} post-ID destinations`);
